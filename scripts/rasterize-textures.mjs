// Development only: bake the original SVG filter textures once, keeping their appearance.
// The committed PNGs are bundled by esbuild; deployment does not need a browser.
import { chromium } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const source = await readFile(new URL('../index.html', import.meta.url), 'utf8');
const textures = [...source.matchAll(/(--tx-[a-z0-9-]+):url\("(data:image\/svg\+xml,[^"]+)"\)/g)];
const directory = new URL('../client/textures/', import.meta.url);
await mkdir(directory, {recursive:true});
const browser = await chromium.launch({channel:'msedge', headless:true});
try {
  const page = await browser.newPage();
  const rules = [];
  for (const [,name,url] of textures) {
    const png = await page.evaluate(async url => {
      const image = new Image(); image.src = url; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
      canvas.getContext('2d').drawImage(image, 0, 0);
      return canvas.toDataURL('image/png').split(',')[1];
    }, url);
    const file = name.slice(2) + '.png';
    await writeFile(new URL(file,directory), Buffer.from(png,'base64'));
    rules.push(`  ${name}:url('./textures/${file}');`);
  }
  await writeFile(new URL('../client/textures.css',import.meta.url),
    '/* Generated by scripts/rasterize-textures.mjs from the original theme textures. */\nbody.server-mode.medieval{\n'+rules.join('\n')+'\n}\n');
  console.log(`Baked ${textures.length} theme textures.`);
} finally { await browser.close(); }
